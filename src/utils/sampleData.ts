export function resolveUserPermissions(
  role: AdminRoleType,
  custom?: Partial<Record<PermissionKey, boolean>>
): Record<PermissionKey, boolean> {
  let base: Record<PermissionKey, boolean>;
  if (role === 'primary_admin') {
    base = { ...PRIMARY_ADMIN_PERMISSIONS };
  } else if (role === 'senior_admin') {
    // Role Inheritance: automatically inherits all junior admin permissions
    base = { ...JUNIOR_ADMIN_BASE_PERMISSIONS, ...SENIOR_ADMIN_ADDITIONAL_PERMISSIONS };
  } else if (role === 'junior_admin') {
    base = { ...JUNIOR_ADMIN_BASE_PERMISSIONS };
  } else {
    base = { ...TEACHER_PERMISSIONS };
  }
  if (custom) {
    base = { ...base, ...custom };
  }
  return base;
}

